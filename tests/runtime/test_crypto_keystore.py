def test_keys_autogenerated_and_persisted(monkeypatch, tmp_path):
    """No secret env vars at all -> generated keyring persisted 0600 and
    stable across calls; env vars always override the file."""
    from lnbits.settings import settings as host_settings

    for name in (
        "INFINITEMARKETS_MASTER_KEYS",
        "INFINITEMARKETS_PRIVACY_KEY",
        "INFINITEMARKETS_ACTIVE_KEY_VERSION",
    ):
        monkeypatch.delenv(name, raising=False)
    monkeypatch.setenv("INFINITEMARKETS_PUBLIC_BASE_URL", "https://x.example")
    monkeypatch.setattr(host_settings, "lnbits_data_folder", str(tmp_path))

    first = gsettings.ext_settings()
    assert first.keys_autogenerated
    assert first.active_key_version == "v1"
    keyfile = tmp_path / "infinitemarkets-keys.json"
    assert keyfile.is_file()
    assert (keyfile.stat().st_mode & 0o777) == 0o600

    second = gsettings.ext_settings()
    assert second.keys_autogenerated
    assert second.master_keys == first.master_keys
    assert second.privacy_key == first.privacy_key
    assert first.privacy_key not in first.master_keys.values()

    import json

    monkeypatch.setenv(
        "INFINITEMARKETS_MASTER_KEYS",
        json.dumps({"v1": base64.b64encode(bytes(32)).decode()}),
    )
    monkeypatch.setenv(
        "INFINITEMARKETS_PRIVACY_KEY",
        base64.b64encode(bytes([9]) * 32).decode(),
    )
    explicit = gsettings.ext_settings()
    assert not explicit.keys_autogenerated
    assert explicit.master_keys["v1"] == bytes(32)


